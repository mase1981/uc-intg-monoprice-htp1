#!/usr/bin/env python3
"""Transform the upstream BEQ database into a compact, versioned static catalogue.

The source database is intentionally parsed only in CI. The Remote downloads the
small browse index and individual filter payloads on demand.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import shutil
from collections import defaultdict
from pathlib import Path
from typing import Any

SCHEMA_VERSION = 1
FILTER_FIELDS = ("type", "freq", "gain", "q")
SUPPORTED_FILTER_TYPES = {"PeakingEQ", "LowShelf", "HighShelf"}
MAX_FILTERS = 16
# Match the HTP-1 BEQ application path: imported values are normalized to
# the processor's effective limits, rather than rejected at the PEQ editor's
# narrower manual-entry limits.
MIN_FREQUENCY = 10
MAX_FREQUENCY = 20000
MIN_GAIN = -99
MAX_GAIN = 20
MIN_Q = 0.1
MAX_Q = 10


class IncompatibleCatalogueEntry(ValueError):
    """A valid BEQ record not supported by the current integration."""

    def __init__(self, title: str, author: str, year: str, content_type: str, issues: list[dict[str, Any]]):
        super().__init__(f"BEQ entry {title!r} is incompatible with HTP-1 PEQ")
        self.report = {
            "title": title,
            "author": author,
            "year": year,
            "content_type": content_type,
            "issues": issues,
        }


def _canonical(value: Any) -> bytes:
    return json.dumps(value, separators=(",", ":"), sort_keys=True).encode("utf-8")


def _compact_record(
    record: dict[str, Any],
) -> tuple[dict[str, Any], dict[str, Any], list[dict[str, Any]]]:
    title = record.get("title")
    if not isinstance(title, str) or not title.strip():
        raise ValueError("record has no valid title")

    raw_filters = record.get("filters", [])
    if not isinstance(raw_filters, list):
        raise ValueError(f"record {title!r} has invalid filters")

    filters: list[dict[str, Any]] = []
    issues: list[dict[str, Any]] = []
    adjustments: list[dict[str, Any]] = []
    for filter_index, raw_filter in enumerate(raw_filters):
        if not isinstance(raw_filter, dict):
            raise ValueError(f"record {title!r} contains a non-object filter")
        item = {field: raw_filter[field] for field in FILTER_FIELDS if field in raw_filter}
        if not all(field in item for field in FILTER_FIELDS):
            raise ValueError(f"record {title!r} contains an incomplete filter")
        if not isinstance(item["type"], str):
            raise ValueError(f"record {title!r} has an invalid filter type")
        for field in ("freq", "gain", "q"):
            value = item[field]
            if isinstance(value, bool) or not isinstance(value, (int, float)):
                raise ValueError(f"record {title!r} has a non-numeric filter {field}")
            try:
                finite = math.isfinite(value)
            except OverflowError:
                finite = False
            if not finite:
                raise ValueError(f"record {title!r} has a non-finite filter {field}")
        reasons = []
        if item["type"] not in SUPPORTED_FILTER_TYPES:
            reasons.append(f"filter type not supported by integration: {item['type']}")
        if reasons:
            issues.append({
                "filter_index": filter_index,
                "type": item["type"],
                "reasons": reasons,
            })

        for field, lower, upper in (
            ("freq", MIN_FREQUENCY, MAX_FREQUENCY),
            ("gain", MIN_GAIN, MAX_GAIN),
            ("q", MIN_Q, MAX_Q),
        ):
            original = item[field]
            applied = min(max(original, lower), upper)
            if applied != original:
                adjustments.append({
                    "filter_index": filter_index,
                    "type": item["type"],
                    "field": field,
                    "original": original,
                    "applied": applied,
                })
                item[field] = applied
        filters.append(item)

    if len(filters) > MAX_FILTERS:
        issues.append({
            "filter_count": len(filters),
            "reasons": [f"entry has more than {MAX_FILTERS} filters per channel"],
        })

    underlying = record.get("underlying") or ""
    if not isinstance(underlying, str):
        raise ValueError(f"record {title!r} has invalid underlying identifier")
    legacy_id_filters = [
        {key: value for key, value in raw_filter.items() if key != "biquads"}
        for raw_filter in raw_filters
    ]
    compact_payload = {
        "title": title,
        "underlying": underlying,
        "filters": legacy_id_filters,
    }
    # Preserve the media IDs generated by the previous integration implementation.
    entry_id = hashlib.md5(_canonical(compact_payload)).hexdigest()[:16]
    entry_payload = {"title": title, "underlying": underlying, "filters": filters}

    audio_types = record.get("audioTypes") or []
    if not isinstance(audio_types, list):
        raise ValueError(f"record {title!r} has invalid audioTypes")
    content_type = record.get("content_type") or "other"
    if not isinstance(content_type, str):
        raise ValueError(f"record {title!r} has invalid content_type")

    if issues:
        raise IncompatibleCatalogueEntry(
            title,
            str(record.get("author") or ""),
            str(record.get("year") or ""),
            content_type,
            issues,
        )

    index_item = {
        "id": entry_id,
        "title": title,
        "author": str(record.get("author") or ""),
        "year": str(record.get("year") or ""),
        "audioTypes": [str(value) for value in audio_types],
        "content_type": content_type,
    }
    return index_item, entry_payload, adjustments


def build(source: Path, output: Path) -> dict[str, Any]:
    raw = source.read_bytes()
    records = json.loads(raw)
    if not isinstance(records, list) or not records:
        raise ValueError("source catalogue must be a non-empty JSON array")

    source_digest = hashlib.sha256(raw).hexdigest()
    version = source_digest[:16]
    # The source can be tens of megabytes. Do not retain its raw byte buffer
    # throughout transformation once JSON decoding has completed.
    del raw
    entries_dir = output / version / "entries"
    entries_dir.mkdir(parents=True, exist_ok=True)

    index_entries: list[dict[str, Any]] = []
    filterless_entries: list[dict[str, str]] = []
    unsupported_entries: list[dict[str, Any]] = []
    adjusted_entries: list[dict[str, Any]] = []
    for record in records:
        if not isinstance(record, dict):
            raise ValueError("source catalogue contains a non-object record")
        try:
            item, payload, adjustments = _compact_record(record)
        except IncompatibleCatalogueEntry as err:
            unsupported_entries.append(err.report)
            continue
        if adjustments:
            adjusted_entries.append({
                "title": item["title"],
                "author": item["author"],
                "year": item["year"],
                "content_type": item["content_type"],
                "adjustments": adjustments,
            })
        if not payload["filters"]:
            filterless_entries.append({
                "title": item["title"],
                "author": item["author"],
                "year": item["year"],
                "content_type": item["content_type"],
            })
            continue
        index_entries.append(item)
        (entries_dir / f"{item['id']}.json").write_bytes(_canonical(payload))

    filterless_entries.sort(key=lambda item: (
        item["title"].casefold(), item["author"].casefold(), item["year"]
    ))
    filterless_report = {
        "source_version": version,
        "count": len(filterless_entries),
        "entries": filterless_entries,
    }
    (output / "filterless-entries.json").write_bytes(_canonical(filterless_report))
    report_lines = [
        "BEQ catalogue entries without filters",
        f"Source version: {version}",
        f"Excluded entries: {len(filterless_entries)}",
        "",
    ]
    report_lines.extend(
        f"{entry['title']}"
        + (f" — {entry['author']}" if entry["author"] else "")
        + (f" ({entry['year']})" if entry["year"] else "")
        + f" [{entry['content_type']}]"
        for entry in filterless_entries
    )
    (output / "filterless-entries.txt").write_text(
        "\n".join(report_lines) + "\n", encoding="utf-8"
    )

    unsupported_entries.sort(key=lambda item: (
        item["title"].casefold(), item["author"].casefold(), item["year"]
    ))
    unsupported_report = {
        "source_version": version,
        "count": len(unsupported_entries),
        "entries": unsupported_entries,
    }
    (output / "unsupported-entries.json").write_bytes(_canonical(unsupported_report))
    unsupported_lines = [
        "BEQ catalogue entries not supported by the current integration",
        f"Source version: {version}",
        f"Excluded entries: {len(unsupported_entries)}",
        "",
    ]
    for entry in unsupported_entries:
        label = entry["title"] + (f" — {entry['author']}" if entry["author"] else "")
        for issue in entry["issues"]:
            reasons = "; ".join(issue["reasons"])
            filter_label = f"filter {issue['filter_index'] + 1}" if "filter_index" in issue else "filter count"
            unsupported_lines.append(f"{label}: {filter_label}: {reasons}")
    (output / "unsupported-entries.txt").write_text(
        "\n".join(unsupported_lines) + "\n", encoding="utf-8"
    )

    adjusted_entries.sort(key=lambda item: (
        item["title"].casefold(), item["author"].casefold(), item["year"]
    ))
    adjusted_report = {
        "source_version": version,
        "count": len(adjusted_entries),
        "entries": adjusted_entries,
    }
    (output / "adjusted-entries.json").write_bytes(_canonical(adjusted_report))
    adjusted_lines = [
        "BEQ catalogue entries with values normalized to HTP-1 BEQ limits",
        f"Source version: {version}",
        f"Adjusted entries: {len(adjusted_entries)}",
        "",
    ]
    for entry in adjusted_entries:
        label = entry["title"] + (f" — {entry['author']}" if entry["author"] else "")
        for adjustment in entry["adjustments"]:
            adjusted_lines.append(
                f"{label}: filter {adjustment['filter_index'] + 1} "
                f"{adjustment['field']} {adjustment['original']} -> {adjustment['applied']}"
            )
    (output / "adjusted-entries.txt").write_text(
        "\n".join(adjusted_lines) + "\n", encoding="utf-8"
    )

    index_entries.sort(key=lambda item: (
        item["title"].casefold(), item["author"].casefold(), item["id"]
    ))
    category_indexes: dict[str, list[int]] = defaultdict(list)
    for entry_index, item in enumerate(index_entries):
        category_indexes[item["content_type"]].append(entry_index)
    index = {
        "schema_version": SCHEMA_VERSION,
        "version": version,
        "entries": [
            {key: value for key, value in item.items() if key != "content_type"}
            for item in index_entries
        ],
        "categories": dict(sorted(category_indexes.items())),
    }
    index_bytes = _canonical(index)
    (output / version / "index.json").write_bytes(index_bytes)
    manifest = {
        "schema_version": SCHEMA_VERSION,
        "version": version,
        "source_sha256": source_digest,
        "entry_count": len(index_entries),
        "filterless_count": len(filterless_entries),
        "filterless_report": "filterless-entries.json",
        "unsupported_count": len(unsupported_entries),
        "unsupported_report": "unsupported-entries.json",
        "adjusted_count": len(adjusted_entries),
        "adjusted_report": "adjusted-entries.json",
        "index": f"{version}/index.json",
        "index_sha256": hashlib.sha256(index_bytes).hexdigest(),
    }
    (output / "manifest.json").write_bytes(_canonical(manifest))
    return manifest


def _reset_output_directory(output: Path) -> None:
    """Replace generated output without following symlinks or deleting the working tree."""
    resolved = output.resolve()
    if resolved == Path(resolved.anchor) or resolved == Path.cwd().resolve():
        raise ValueError(f"refusing to replace unsafe output directory: {output}")
    if output.is_symlink() or (output.exists() and not output.is_dir()):
        output.unlink()
    elif output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    _reset_output_directory(args.output)
    manifest = build(args.source, args.output)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
